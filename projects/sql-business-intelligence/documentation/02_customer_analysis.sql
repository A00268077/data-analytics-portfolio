- Segment
- Country
- Market
- First Order Date
- Last Order Date
- Completed Orders
- Units Purchased
- Lifetime Revenue
- Lifetime Cost
- Lifetime Gross Profit
- Gross Margin %
- Average Order Value
- Purchase Status
- Days Since Last Order
- Activity Status

This dataset can later be converted into a PostgreSQL view and connected directly to Power BI.

