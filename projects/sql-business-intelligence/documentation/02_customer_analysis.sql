## Key Customer Insights

### Highest-Value Customers

The highest-value customer generated approximately **€18.55K** in completed-order revenue.

The Top 20 customer group is relatively broad rather than being dominated by one single account, which reduces dependency on an individual customer.

Ireland is strongly represented among the highest-value customers, while the Consumer segment dominates the top customer ranking.

### Customer Lifetime Value

Customer Lifetime Value analysis shows meaningful variation across customers in both total revenue and average order value.

Some customers place more frequent orders, while others generate fewer but significantly higher-value purchases.

This distinction helps separate high-frequency customers from high-ticket customers.

### Repeat Purchasing Behaviour

Repeat-customer analysis measures how many customers completed more than one order and provides a direct indication of retention and purchasing loyalty.

The repeat-customer rate can be used as a management KPI to evaluate whether the customer base is primarily transactional or relationship-driven.

### Revenue Concentration

Customer revenue concentration analysis measures the share of total company revenue generated by each individual customer.

This helps identify whether the business depends heavily on a small number of accounts or whether revenue is broadly distributed.

### Pareto 80/20 Analysis

The Pareto analysis ranks customers by revenue and calculates cumulative revenue contribution.

This allows management to identify the number and percentage of customers required to generate approximately 80% of company revenue.

It also enables comparison with the classic 80/20 assumption and shows the actual concentration pattern in this dataset.

### Customer Segment Performance

Customer segments are compared using:

- Customer count
- Completed orders
- Units purchased
- Revenue
- Gross profit
- Gross margin
- Average order value

This identifies which segments contribute the most commercial value and whether higher revenue segments also generate stronger profitability.

### Geographic Customer Performance

Customer performance by country and market highlights geographic differences in:

- Revenue
- Gross profit
- Revenue per customer
- Average order value

This supports geographic customer strategy and market prioritisation.

### Purchase Frequency

Purchase-frequency analysis distinguishes occasional customers from highly engaged repeat buyers.

Customers with high completed-order counts can be prioritised for loyalty, retention, and account-development initiatives.

### Inactive Customers

Customers with no completed purchase during the final 12 months of the analytical period are classified as inactive.

This provides a simple operational list for reactivation campaigns and churn analysis.

### Customer Recency and Churn Risk

Customers are classified into four activity groups:

- Active
- Watch
- At Risk
- Inactive

Customers who have never completed a purchase are identified separately.

This creates a practical churn-risk proxy that can later be used in Power BI or customer-retention reporting.

### High Average Order Value Customers

Customers with the highest average order value are not necessarily the same customers with the highest total revenue.

This distinction helps identify premium customers who purchase less frequently but place larger orders.

### New vs Repeat Customer Revenue

Completed orders are classified as either:

- New Customer
- Repeat Customer

This analysis shows how much revenue is generated from customer acquisition compared with existing-customer retention.

### Customer Profitability

Customers are also ranked by gross profit rather than revenue alone.

This demonstrates that high revenue does not always imply the highest profitability and helps identify the customers creating the greatest economic value.

### Customer Value Tiers

Customers are divided into quartiles using `NTILE(4)`:

- Tier 1 - High Value
- Tier 2 - Upper Mid Value
- Tier 3 - Lower Mid Value
- Tier 4 - Low Value

These tiers provide a practical customer segmentation layer for targeted reporting and commercial decision-making.

