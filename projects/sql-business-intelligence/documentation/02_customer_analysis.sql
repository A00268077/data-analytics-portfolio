# Customer Analysis Module

## Overview

This module analyses customer value, purchasing behaviour, retention, profitability, revenue concentration, and customer activity using PostgreSQL.

The SQL file `02_customer_analysis.sql` contains a set of business-focused queries designed to help management understand who the most valuable customers are, how frequently customers return, how concentrated revenue is across the customer base, and which customers may require retention attention.

The analysis uses completed orders as realised sales and treats **2025-12-31** as the analytical reference date for recency and inactivity calculations.

---

## Business Objectives

This module answers the following questions:

- Who are the highest-value customers?
- Which customers generate the most revenue?
- How many customers make repeat purchases?
- What is the repeat customer rate?
- How concentrated is revenue across the customer base?
- How many customers are required to generate 80% of total revenue?
- Which customer segments perform best?
- Which countries contain the strongest customer base?
- How frequently do customers place orders?
- Which customers are inactive?
- Which customers are at risk of becoming inactive?
- Which customers have the highest average order value?
- How much revenue comes from new versus repeat customers?
- Which customers generate the most gross profit?
- How much revenue is generated by the top 20% of customers?
- How can customers be grouped into value tiers?
- What customer-level dataset can be used in Power BI?

